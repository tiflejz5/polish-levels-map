/*
 * exercise-engine.js — the exercise engine: a set session (Learn / Exam mode),
 * ten item types (paradigm = "Fill the table", spec 06 E6), the result screen, the “Check yourself” section on topic pages.
 * Item types: the reference engine's spec (docs/rozbudowa-v2/spec/01-typy-zadan.md); types gap-fill, match,
 * transformation, translate, dictation and scores in points: docs/rozbudowa-v6/spec/12-nowe-typy-zadan.md.
 *
 * Routes:
 *   #/practice[/mixes]             Practice (js/practice-hub.js)
 *   #/practice/set/<setId>         a set from content/exercises/
 *   #/practice/mix/<mixId>         a ready mixed set
 *   #/practice/session             a set drawn by the generator (Practice)
 *   #/practice/weak[/<topic>]      weak-spot practice (spec 03, point 5)
 *
 * Data is loaded ON DEMAND with a plain <script> (works from file://):
 *   data/sets-index.js → LM.SETS_INDEX (map, set descriptions, mixes)
 *   data/sets/<id>.js  → LM.SETS[<id>]
 * The files are generated by npm run build (tools/build/exercises.js).
 *
 * Results: LM.profileData (key plm.exercises, separately per profile).
 * Logic without DOM (grading, shuffling, drawing mixes): js/exercise-logic.js.
 * Answers typed by the user go into the page only as text.
 */
