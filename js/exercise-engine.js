  /** The exercise index (Promise). No file → an empty index, the app keeps working. */
  function loadIndex() {
    if (LM.SETS_INDEX) return Promise.resolve(LM.SETS_INDEX);
    return LM.loadModule("data/sets-index.js").then(function () {
      return LM.SETS_INDEX || emptyIndex();
    }, function (e) {
      console.warn(e.message + " — run: npm run build");
      return emptyIndex();
    });
  }

  function emptyIndex() { return { topics: {}, sets: {}, mixes: [], tenseByTopic: {} }; }

  /** Full sets with the given ids (skips missing files with a warning). */
  function loadSets(ids) {
    return loadIndex().then(function (index) {
      return Promise.all(ids.map(function (id) {
        const meta = index.sets[id];
        if (!meta) { console.warn("Practice: no set " + id); return null; }
        if (LM.SETS && LM.SETS[id]) return LM.SETS[id];
        return LM.loadModule(meta.file).then(function () {
          return (LM.SETS && LM.SETS[id]) || null;
        }, function (e) { console.warn(e.message); return null; });
      }));
    }).then(function (list) { return list.filter(Boolean); });
  }

  /** Items of the sets of the given topics (for mixes and the generator). */
  function loadTopicItems(topics) {
    return loadIndex().then(function (index) {
      const ids = [];
      topics.forEach(function (t) { (index.topics[t] || []).forEach(function (id) { if (ids.indexOf(id) === -1) ids.push(id); }); });
      return loadSets(ids);
    }).then(function (sets) {
      return [].concat.apply([], sets.map(function (s) { return s.items; }));
    });
  }

  /** Pool for drawing (mixes, generator, weak spots): without dictations when the browser has no target-language voice. */
  function playablePool(pool) {
    return noTargetVoice() ? pool.filter(function (it) { return it.type !== "dictation"; }) : pool;
  }

  /** A topic by id: { id, level, title, href } or null. */
  function topicInfo(id) {
    return id && LM.mistakes ? LM.mistakes.findItem(id) : null;
  }

  /** Short description of the types: “multiple choice, put in order”. */
  function typesText(types) {
    return Object.keys(types).map(function (t) { return TYPE_SHORT[t] || t; }).join(", ");
  }

  function scoreText(s) { return s.score + "/" + s.total; }

