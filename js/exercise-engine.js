  function onEnter() {
    if (run && run.missing) { run = null; return; } // e.g. weak spots may have appeared by now
    if (!run || run.phase !== "done") return;
    if (/^(mix|weak|final):/.test(run.key)) run = null; // mix / practice / final test: a new draw on the next visit
    else if (!run.isMix) newRun(Object.assign({}, run, { items: run.source, retry: false }));
  }

  // =====================================================================
  // KEYBOARD: Enter = Check / Next, numbers 1–4 = options, Backspace = take back a word
  // =====================================================================

  document.addEventListener("keydown", function (e) {
    if (!run || run.phase !== "item" || e.altKey) return;
    if (!document.querySelector(".ex-view .ex-card")) return;
    const p = run.items[run.i];
    const t = e.target;
    const typing = t && (t.tagName === "TEXTAREA" || (t.tagName === "INPUT" && t.type === "text"));
    // Ctrl/Cmd+Enter = Check (multi-line fields: translation, dictation); other Ctrl/Cmd shortcuts stay with the browser
    if (e.ctrlKey || e.metaKey) {
      if (e.key === "Enter" && typing) { e.preventDefault(); check(); }
      return;
    }
    if (e.key === "Enter") {
      // On buttons Enter works natively; in a text field and on options = Check; Shift+Enter in a multi-line field = a new line
      if (t && t.tagName === "BUTTON" || t && t.tagName === "A") return;
      if (e.shiftKey && t && t.tagName === "TEXTAREA") return;
      e.preventDefault();
      check();
      return;
    }
    // S: listen to the sentence (before checking a gap is a pause), works after checking too; not in text fields
    if (!typing && (e.key === "s" || e.key === "S")) {
      const text = X().speechText(p.item, !!p.res);
      if (text && (p.item.kind !== "listening")) { e.preventDefault(); if (LM.shortcuts) LM.shortcuts.speak(text); }
      return;
    }
    if (p.res || typing) return;
    if (p.item.type === "match" && /^[1-9]$/.test(e.key)) {
      // Numbers choose an item of the right column (after choosing a left one)
      const i = Number(e.key) - 1;
      if (i < p.right.length && p.st.sel && p.st.sel.side === "left") {
        e.preventDefault();
        matchPick(p, "right", i);
        // Focus on the next left item without a pair (fast pairing from the keyboard); all connected → “Check”
        const k = p.item.pairs.findIndex(function (_, j) { return p.st.pairs[j] === undefined; });
        repaint(k === -1 ? "check" : k === 0 ? "first" : "L" + k);
      }
      return;
    }
    if (p.item.type === "multiple-choice" && (/^[1-9]$/.test(e.key) || /^[a-hA-H]$/.test(e.key))) {
      const opts = p.choice.options;
      let i = -1;
      if (/^[1-9]$/.test(e.key)) i = Number(e.key) - 1;
      else if (opts.every(function (o) { return /^[A-H]$/.test(String(o.text).trim()); })) i = opts.findIndex(function (o) { return String(o.text).trim() === e.key.toUpperCase(); }); // the options are letters only (reading parts): a letter = the option with that text
      else i = e.key.toLowerCase().charCodeAt(0) - 97; // A–D = the first to the fourth option
      if (i >= 0 && i < opts.length) { e.preventDefault(); p.st.chosen = i; repaint(i === 0 ? "first" : "opt-" + i); }
    } else if (p.item.type === "reorder" && e.key === "Backspace" && p.st.line.length) {
      e.preventDefault();
      p.st.line.pop();
      repaint("first");
    }
  });

